/// : dil + aninda yenileme. Varsayilan = cihaz dili
/// (tr/en/es/de/fr, bilinmeyende en). Ayarlardan kilitle.
class HGorsel {
  static final ValueNotifier<int> nesil = ValueNotifier(0);
  static void yenile() => nesil.value++;
}

class HDil {
  static const String _anahtar = 'hstream_dil';
  static const List<String> kodlar = ['tr', 'en', 'es', 'de', 'fr'];
  /// 'auto' veya kod.
  static String secim = 'auto';

  static String cihaz() {
    final c = WidgetsBinding.instance.platformDispatcher.locale
        .languageCode
        .toLowerCase();
    if (kodlar.contains(c)) return c;
    return 'en';
  }

  static String aktif() => secim == 'auto' ? cihaz() : secim;

  static Future<void> yukle() async {
    final p = await SharedPreferences.getInstance();
    secim = p.getString(_anahtar) ?? 'auto';
    if (secim != 'auto' && !kodlar.contains(secim)) secim = 'auto';
  }

  static Future<void> ayarla(String value) async {
    secim = value;
    final p = await SharedPreferences.getInstance();
    await p.setString(_anahtar, value);
    HGorsel.yenile();
  }
}

